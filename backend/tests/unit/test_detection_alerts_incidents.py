def test_detection_rule_evaluation_and_alert_generation(client, admin_token, db):
    org = db.query(Organization).first()

    # 1. Ingest Log matching Built-in Detection Rule (EHR_BULK_EXPORT)
    ingest_payload = {
        "source_name": "EHR_Audit",
        "raw_content": '{"event_type": "EHR_BULK_EXPORT", "username": "dr_john", "hostname": "EMR-SERVER-01"}',
        "hostname": "EMR-SERVER-01",
        "org_id": str(org.id)
    }
    ingest_resp = client.post("/api/v1/events/ingest", json=ingest_payload)
    assert ingest_resp.status_code == 201

    # 2. Verify Alert was automatically generated by Detection Engine
    alerts_resp = client.get("/api/v1/alerts", headers={"Authorization": f"Bearer {admin_token}"})
    assert alerts_resp.status_code == 200
    alerts = alerts_resp.json()["data"]
    assert len(alerts) >= 1
    generated_alert = alerts[0]

    # 3. Create Incident from Generated Alert
    inc_payload = {
        "title": "INCIDENT #2001 — EHR Unauthorized PHI Bulk Export",
        "description": "Escalation of bulk export alert.",
        "severity": "CRITICAL",
        "status": "OPEN",
        "org_id": str(org.id),
        "alert_ids": [generated_alert["id"]]
    }
    inc_resp = client.post("/api/v1/incidents", json=inc_payload, headers={"Authorization": f"Bearer {admin_token}"})
    assert inc_resp.status_code == 201
    inc_data = inc_resp.json()["data"]
    assert inc_data["severity"] == "CRITICAL"

    # 4. Resolve Alert & Incident
    res_alert = client.post(f"/api/v1/alerts/{generated_alert['id']}/resolve", headers={"Authorization": f"Bearer {admin_token}"})
    assert res_alert.status_code == 200

    res_inc = client.post(f"/api/v1/incidents/{inc_data['id']}/resolve", headers={"Authorization": f"Bearer {admin_token}"})
    assert res_inc.status_code == 200
    assert res_inc.json()["data"]["status"] == "RESOLVED"
